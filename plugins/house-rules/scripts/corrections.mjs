// Finds what the person said to the agents in a Claude Code transcript, with
// what the agent had just done, so `/house-rules:correct` can group repeated
// corrections into classes. Pure: it takes the transcript's lines and returns
// records; scripts/list-corrections.mjs reads the files and prints them.

const MAX_ACTIONS = 6

// Text a user entry carries that the person did not type to the agent: a
// compaction summary, a slash command or its output, a shell escape, or a
// message from another session.
const MACHINE = [
  /^This session is being continued from a previous conversation/,
  /^<(?:command-|local-command-|bash-|system-reminder|task-notification|agent-message)/,
  /^Another Claude session sent a message/,
  /^Caveat: The messages below were generated by the user while running local commands/,
]
const INTERRUPTED = /^\[Request interrupted by user[^\]]*\]$/
const REFUSED = /^The user doesn't want to proceed with this tool use\./
const FEEDBACK = /the user said:\s*([\s\S]*)$/
// A pasted block's tags carry the same id at both ends.
const PASTED = /<pasted_content\b[^>]*>([\s\S]*?)<\/pasted_content\b[^>]*>/g

const parse = line => {
  try {
    return JSON.parse(line)
  } catch {
    return undefined
  }
}

const blocks = entry => {
  const content = entry.message?.content
  if (typeof content === 'string') return [{ type: 'text', text: content }]
  return Array.isArray(content) ? content : []
}

const resultText = block =>
  typeof block.content === 'string'
    ? block.content
    : Array.isArray(block.content)
      ? block.content.filter(part => part.type === 'text').map(part => part.text).join('\n')
      : ''

const oneLine = (text, max) => {
  const flat = text.replace(/\s+/g, ' ').trim()
  return flat.length > max ? `${flat.slice(0, max - 3)}...` : flat
}

// A tool call as a short line: its name and the input that says what it touched.
export const action = block => {
  const input = block.input ?? {}
  const target = input.file_path ?? input.notebook_path ?? input.path ?? input.command ?? input.skill ?? input.subagent_type ?? input.pattern ?? input.url
  return typeof target === 'string' ? `${block.name} ${oneLine(target, 90)}` : block.name
}

const typedBy = entry => {
  if (entry.isMeta || entry.isSidechain || entry.isCompactSummary) return false
  return entry.promptSource === undefined || entry.promptSource === 'typed'
}

// The records of one transcript, in order: each thing the person typed, or a
// tool call they refused with a reason, with the agent's last tool calls before it.
export const correctionsIn = (lines, session) => {
  const records = []
  let actions = []
  let interrupted = false
  let refused
  for (const entry of lines.map(parse)) {
    if (entry === undefined || entry.isSidechain) continue
    if (entry.type === 'assistant') {
      for (const block of blocks(entry)) if (block.type === 'tool_use') actions = [...actions, action(block)].slice(-MAX_ACTIONS)
      continue
    }
    if (entry.type !== 'user') continue
    const parts = blocks(entry)
    const rejected = parts.find(block => block.type === 'tool_result' && REFUSED.test(resultText(block)))
    if (rejected !== undefined) {
      refused = actions.at(-1) ?? 'a tool call'
      const said = FEEDBACK.exec(resultText(rejected))?.[1]?.trim()
      if (said) {
        records.push({ at: entry.timestamp ?? '', session, after: actions, refused, interrupted, said: oneLine(said, 600) })
        actions = []
        interrupted = false
        refused = undefined
      }
      continue
    }
    if (parts.some(block => block.type === 'tool_result')) continue
    const text = parts
      .filter(block => block.type === 'text')
      .map(block => block.text)
      .join('\n')
      .trim()
    if (INTERRUPTED.test(text)) {
      interrupted = true
      continue
    }
    if (!text || !typedBy(entry) || MACHINE.some(rule => rule.test(text))) continue
    const said = text.replace(PASTED, (_, pasted) => `[pasted ${pasted.length} characters]`)
    records.push({ at: entry.timestamp ?? '', session, after: actions, refused, interrupted, said: oneLine(said, 600) })
    actions = []
    interrupted = false
    refused = undefined
  }
  return records
}

// The folder Claude Code keeps a project's transcripts in: its path, every
// character that is not a letter or a digit made a dash.
export const transcriptFolderName = project => project.replace(/[^A-Za-z0-9]/g, '-')

export const format = (records, project) => {
  if (records.length === 0) return `No corrections found in the transcripts of ${project}.`
  const sessions = new Set(records.map(record => record.session)).size
  const lines = [`${records.length} messages to the agents in ${sessions} sessions of ${project}, oldest first.`]
  for (const record of records) {
    lines.push('', `[${record.at.slice(0, 16).replace('T', ' ')}] session ${record.session}`)
    if (record.after.length > 0) lines.push(`  After: ${record.after.join('; ')}`)
    if (record.interrupted) lines.push('  The person interrupted the agent first.')
    if (record.refused !== undefined) lines.push(`  The person refused: ${record.refused}`)
    lines.push(`  Said: ${record.said}`)
  }
  return lines.join('\n')
}
